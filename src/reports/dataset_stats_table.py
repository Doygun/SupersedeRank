from __future__ import annotations

import json
import sys
from pathlib import Path

from src import paths
from src.timeline.config import load_timeline_config

TABLES = paths.PAPER_TABLES_DIR

def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))

def fmt(n: int | float) -> str:
    return f"{n:,}".replace(",", "\\,")

def dataset_stats() -> str:
    manifest = _load(paths.PROCESSED_DATA_DIR / "splits" / "manifest.json")
    split = _load(paths.DATA_PROFILE_DIR / "temporal_split_profile.json")
    cand = _load(paths.DATA_PROFILE_DIR / "cvss_replacement_profile.json")
    scope = manifest["scope"]
    counts = manifest["counts"]
    s = split["splits"]

    strict = cand["tier_counts"]["STRICT"]
    excluded_cand = cand["tier_counts"].get("EXCLUDED", 0)
    rows_pipeline = [
        ("CVSS replacement candidates (Removed+Added in one change)", cand["candidates"]),
        ("STRICT same-change candidates", strict),
        ("Excluded at candidate level (no metric change)", excluded_cand),
        ("Timeline-eligible main events", scope["timeline_eligible_events"]),
        ("Excluded at timeline level (chain ambiguity)", scope["timeline_excluded_events"]),
        ("Main train/dev/test events", scope["main_split_events"]),
        ("Future-event cohort (secondary)", scope["future_event_events"]),
        ("Unique CVEs in main dataset", split["cves_with_main_events"]),
    ]
    rows_split = [
        ("Train", counts["train"]["cves"], counts["train"]["events"], "2024--2025", s["train"]["censored_ratio"]),
        ("Dev (15\\% of train-period CVEs)", counts["dev"]["cves"], counts["dev"]["events"], "2024--2025", s["dev"]["censored_ratio"]),
        ("Test (future-entity)", counts["test"]["cves"], counts["test"]["events"], "2026", s["test"]["censored_ratio"]),
        ("Future-event (secondary, held out)", counts["future_event"]["cves"], counts["future_event"]["events"], "2026", s["future_event"]["censored_ratio"]),
    ]
    lines = [
        "% Auto-generated by src/reports/dataset_stats_table.py -- do not edit by hand.",
        "\\begin{table}\\centering\\small",
        "\\caption{Dataset construction and temporal split.}\\label{tab:veri}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{@{}lr@{}}\\toprule",
        "Stage & Count \\\\\\midrule",
    ]
    lines += [f"{name} & {fmt(n)} \\\\" for name, n in rows_pipeline]

    lines += [
        "\\midrule",
        "\\multicolumn{2}{@{}l}{All eligible atomic events} \\\\",
        "\\quad Split & CVEs / events (years; left-censored share) \\\\\\midrule",
    ]
    lines += [f"\\quad {name} & {fmt(c)} / {fmt(e)} ({years}; {r*100:.1f}\\%) \\\\" for name, c, e, years, r in rows_split]
    bq_path = paths.PROCESSED_DATA_DIR / "splits" / "base_query_eligible_manifest.json"
    if bq_path.exists():
        bq = _load(bq_path)
        ex = bq["excluded_by_detail"]
        lines += [
            "\\midrule",
            "\\multicolumn{2}{@{}l}{Base-query-eligible subset} \\\\",
            "\\quad Split & CVEs / events (= main queries) \\\\\\midrule",
            f"\\quad Excluded: threat-only / supplemental-only / environmental-only / mixed non-base & "
            f"{fmt(ex.get('THREAT_ONLY_CHANGE', 0))} / {fmt(ex.get('SUPPLEMENTAL_ONLY_CHANGE', 0))} / "
            f"{fmt(ex.get('ENVIRONMENTAL_ONLY_CHANGE', 0))} / {fmt(ex.get('NO_BASE_COMPONENT_CHANGE', 0))} \\\\",
        ]
        for name, key in (("Train", "train"), ("Dev", "dev"), ("Test (future-entity)", "test"), ("Future-event (secondary)", "future_event")):
            lines.append(f"\\quad {name} & {fmt(bq['counts'][key]['cves'])} / {fmt(bq['counts'][key]['events'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    return "\n".join(lines) + "\n"

def timeline_stats() -> str:
    cfg = load_timeline_config()
    t = _load(paths.DATA_PROFILE_DIR / "timeline_profile.json")
    v = _load(paths.PROJECT_ROOT / "results" / "quality_assurance" / "cvss_score_validation.json")
    rows = [
        ("Evidence intervals (all supported CVSS chains, all CVEs)", t["evidence_intervals"]),
        ("Source chains $(\\text{CVE}, \\text{version}, \\text{source})$", t["chains"]),
        ("CVEs with 1 / 2 / $\\geq$3 assessment sources",
         f"{fmt(t['cves_by_source_count']['1'])} / {fmt(t['cves_by_source_count']['2'])} / {fmt(t['cves_by_source_count']['3+'])}"),
        ("Left-censored intervals", t["left_censoring"]["censored_intervals"]),
        ("Atomic same-change replacements (STRICT)", t["replacement_type_counts"]["STRICT_SAME_CHANGE"]),
        ("Cross-event candidates (not in main dataset)", t["replacement_type_counts"].get("HIGH_CONFIDENCE_CROSS_EVENT", 0)),
        ("Same-value removal/re-addition (negative control)", t["same_value_readds"]),
        ("Ambiguous chains (excluded)", t["ambiguous_chains"]),
        ("CVSS 2.0/3.x scores matching NVD (checked / mismatched)",
         f"{fmt(sum(v['matched'].values()))} / {fmt(sum(v['mismatched'].values()) if v['mismatched'] else 0)}"),
    ]
    lines = [
        "% Auto-generated by src/reports/dataset_stats_table.py -- do not edit by hand.",
        "\\begin{table}\\centering\\small",
        "\\caption{CVSS timeline statistics.}\\label{tab:zaman}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}lr@{}}\\toprule",
        "Quantity & Value \\\\\\midrule",
    ]
    lines += [f"{name} & {fmt(n) if isinstance(n, int) else n} \\\\" for name, n in rows]
    lines += ["\\bottomrule", "\\end{tabular*}", "\\end{table}"]
    return "\n".join(lines) + "\n"

def query_profile() -> str:
    q = _load(paths.DATA_PROFILE_DIR / "query_profile.json")
    rows = [("Queries (post-replacement main / pre-replacement control)", f"{fmt(q['by_role']['POST_REPLACEMENT_MAIN'])} / {fmt(q['by_role']['PRE_REPLACEMENT_CONTROL'])}")]
    rows += [(f"Template: {k.replace(chr(95), chr(92) + chr(95))}", fmt(v)) for k, v in sorted(q["by_template"].items())]
    rows += [(f"CVSS version {k}", fmt(v)) for k, v in sorted(q["by_version"].items(), key=lambda kv: -kv[1])]
    rows += [("Queries with an OTHER\\_SOURCE\\_CURRENT candidate", fmt(q["queries_with_other_source_current"])),
             ("Left-censored target evidence (yes / no)", f"{fmt(q['censored_target']['true'])} / {fmt(q['censored_target']['false'])}"),
             ("Mean visible same-CVE evidence per query", f"{q['mean_visible_same_cve_evidence']:.3f}")]
    lines = ["% Auto-generated by src/reports/dataset_stats_table.py -- do not edit by hand.", "\\begin{table}\\centering\\small",
             "\\renewcommand{\\arraystretch}{1.15}", "\\caption{Query template, CVSS version and censoring distribution.}\\label{tab:sorguprofil}", "\\begin{tabular}{@{}lr@{}}\\toprule", "Quantity & Value \\\\\\midrule"]
    lines += [f"{name} & {v} \\\\" for name, v in rows]
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"

def main() -> int:
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "dataset_stats.tex").write_text(dataset_stats(), encoding="utf-8")
    (TABLES / "timeline_stats.tex").write_text(timeline_stats(), encoding="utf-8")
    (TABLES / "query_profile.tex").write_text(query_profile(), encoding="utf-8")
    print(f"yazildi: {TABLES / 'dataset_stats.tex'}, {TABLES / 'timeline_stats.tex'}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
